# -*- coding: utf-8 -*-
"""产物版式 —— 交付件的一份规格（Word 文书 · 幻灯片）。改版式只改这一个文件。

## 两套版式，一份身份

Word 那一套在下面「一 ~ 七」；幻灯片那一套在文件末尾的「幻灯片（Deck）」段。
分成两段而不是两个文件：墨色 / 强调色 / 字体族是同一份身份 ——
同一份材料里的讲义与正文要是两个颜色、两种字体，一眼就看出是两拨人做的。
幻灯片只另起"页"这件事（画布 / 安全边距 / 字号阶梯），别的都从上面借。

## 为什么单独一个文件

「产物长什么样」和「文件写到哪儿」（`core/workspace.py`）是同一类问题：
散在各处就会漂，而两个答案看着都对。所以收成一处，
别的模块只许读它，不许自己写色值和字号。

## 这份规格的理由，逐条写在这儿

不是从哪抄的模板 —— 每一条都要能回答「凭什么」。理由分三类：
中文排版的常识 · 我们当场能验的判据 · 我们自己的取舍。

### 一、字号：锚在中文五号，不锚在"看起来专业"的数

正文 10.5pt（五号）。这是中文正文印了几十年的号数，
换成 9pt 省下的那几行纸，代价是读者眯眼 —— 不值。
其余几级按"层级要看得出来"往上排，不是按等比数列。

### 二、层级不许只靠字号

四样一起动：字号 / 字重 / 颜色 / 间距。
只放大字号是最省事的做法，也是最容易被一眼看出"没设计过"的做法 ——
正文 10.5 到标题 16 只差 5.5pt，光靠它撑不起层级。

### 三、全篇只有一个强调色

章节标题、表头、那条竖条共用一个；正文不用它。
强调色一多，读者就不知道该看哪儿 —— 全都强调等于全都没强调。

选色判据（写下来，免得以后有人随手改）：
够深（当标题色压得住正文）· 饱和度不过高（不刺眼）·
避开饱和的紫蓝（那是最常见的"模板味"，一看见就出戏）。
`#1B3A57` 深钢蓝满足三条。

### 四、正文不用纯黑

`#212121` 而不是 `#000000`。纯黑在长文里"发死"，读久了眼睛累。
标题用强调色、正文用墨色、表注用淡墨 —— 三层就够，不必更多。

### 五、表格要能分清"表头"和"表体"

表头给底纹 + 加粗，框线用发丝线而不是纯黑粗框。
不做隔行斑马纹 —— 中文商务表格的习惯里没有这一条，
行数一多反而花；加它是我们发明的，不是学来的，所以不加。

### 六、数字右对齐

一列数右对齐才比得出大小；中文标签左对齐才读得顺。
判据收得窄：只认纯数、百分比、带千分位/正负号/货币符的 ——
「2025 年」「第一季度」不是数，右对齐更难看。

### 七、页面是 A4 + 中文边距

python-docx 的默认模板是 Letter + 1 英寸，那是美国信纸。
中文交付件按 A4 + 上下 2.5/2.0、左右 2.5cm 来。

## 一处刻意的本地化

涨红跌绿 —— 中文语境的股市惯例，与欧美相反。我们目前不产股票类文档，
但表格里若要标增减，默认按中文口径。写在这儿，免得以后有人按英文惯例写反。
"""

from __future__ import annotations

# 字号（pt）

#: 正文。锚点：中文正文的常识是五号（10.5pt）。
#: 改这一个数，下面几级要跟着重排（判据是"层级差看得见"，不是等比）。
BODY_PT = 10.5

#: 三级标题。只降字号不够 —— 每级同时给字重、颜色与间距（见 `LEVELS`）。
H3_PT = 12.0
H2_PT = 14.0
H1_PT = 16.0

#: 封面（`create_document(title=…)` 有值时，可选开一张）。
COVER_TITLE_PT = 22.0
COVER_SUBTITLE_PT = 14.0

#: 表注 / 图注 / 小字。
CAPTION_PT = 9.0

# 颜色（不带 `#`，python-docx 的 `RGBColor` 认六位十六进制）

#: 正文墨色。不是纯黑 —— 纯黑在长文里发死。
INK = "212121"

#: 淡墨 —— 表注、页脚、次要说明。
INK_MUTED = "616161"

#: 全篇唯一的强调色。章节标题、表头文字、竖条共用它；正文不用。
#: 选它的三条判据见模块 docstring「三」。
ACCENT = "1B3A57"

#: 框线与分隔。发丝线，不是黑粗框。
HAIRLINE = "E0E0E0"

#: 表头底纹。浅到几乎看不见，但足够把表头与表体分开。
TABLE_HEAD_BG = "F0F2F5"

# 排版

#: 正文行距（倍数）。中文长文 1.5~1.7 之间读着最顺。
LINE_SPACING = 1.6

#: 标题行距。标题要紧，才和正文拉得开。
HEADING_LINE_SPACING = 1.25

#: 不首行缩进。中文公文/学术才缩进两字符；商务文档缩进反而业余。
BODY_INDENT_CHARS = 0

#: 章节标题左侧那条竖条（视觉锚点）。宽度单位是八分之一磅（OOXML 的 `w:sz`）：
#: 4px ≈ 3pt，24。
HEADING_BAR = True
HEADING_BAR_SZ = 24

#: 页面。 A4 + 中文边距。
PAGE_WIDTH_CM = 21.0
PAGE_HEIGHT_CM = 29.7
MARGIN_TOP_CM = 2.5
MARGIN_BOTTOM_CM = 2.0
MARGIN_LEFT_CM = 2.5
MARGIN_RIGHT_CM = 2.5

#: 中文字体。一个族：`w:ascii` / `w:hAnsi` / `w:eastAsia` / `w:cs` 四处同值
#: —— 只设 `font.name` 是最常见的"设了没用"（它只写 ascii，中文不受管）。
FONT = "微软雅黑"

#: 正文段后间距（pt）。
PARA_SPACE_AFTER_PT = 6.0


# 组件 —— 让交付件不至于"只有一张表格"
#
# 判据：组件是版式，不是插图。一行提示框、一排指标卡、一条分隔线，
# 全部由底纹 + 边框 + 缩进拼出来 —— 它们可编辑、跟文档一起变，
# 不是画上去的死图。代价小、效果大。

#: 提示框四型：`底色` + `左强调色`。四型都够浅（长文里不刺眼），
#: 靠左侧那一条把性质说清楚 —— 底色只做衬托。
CALLOUT = {
    "info":    ("EEF3F9", "1B3A57"),   # 说明
    "tip":     ("EFF6F2", "1E6B45"),   # 建议
    "warning": ("FDF6EC", "B26A00"),   # 注意
    "danger":  ("FCF0EF", "B3261E"),   # 警告 / 严禁
}

#: 普通引用块（非提示）：中性灰，不抢眼。
QUOTE_BG = "F5F6F8"
QUOTE_BAR = "B9C0C9"

#: 提示框/引用块的内边距（左缩进，pt）—— 段落没有 padding，只能用缩进顶。
BOX_INDENT_PT = 10.0
BOX_SPACE_PT = 6.0

#: 分隔线（`---`）。`w:sz` 单位仍是八分之一磅。
DIVIDER_SZ = 6

#: 指标卡（KPI）：一排大数字。值大、标签小 —— 靠尺寸差与颜色差拉开层级，
#: 而不是把标签也加粗。
KPI_BG = "F5F7FA"
KPI_VALUE_PT = 16.0
KPI_LABEL_PT = 9.0
KPI_CHANGE_PT = 9.0

#: 组件的表要能和"数据表"分开 —— 否则版式体检会把 KPI 卡当成
#: "表头没底纹的表"报红。判据落在 `w:tblCaption` 上（OOXML 里合法的一格）。
COMPONENT_MARK = "lv:component"


# 标题阶梯 —— 四级一起给（字号 / 字重 / 颜色 / 间距），不只动字号

#: `样式名 -> (字号, 段前pt, 段后pt, 带竖条?)`
LEVELS = {
    "Heading 1": (H1_PT, 18.0, 10.0, True),
    "Heading 2": (H2_PT, 14.0, 8.0, True),
    "Heading 3": (H3_PT, 10.0, 6.0, False),
}

#: 封面两个样式 —— 模板里本来就有，可直接使用。
COVER_LEVELS = {
    "Title": (COVER_TITLE_PT, 0.0, 12.0),
    "Subtitle": (COVER_SUBTITLE_PT, 0.0, 6.0),
}


# 幻灯片（Deck）
#
# 为什么另起一段而不是另起一个文件：颜色与字体是同一份身份
#   （见文件头「两套版式，一份身份」），它们是借上面那几个常量，
#   不在这里重写一遍 —— 重写就正是本文件第一段说的那件"散在各处就会漂"。
#   幻灯片自己的只有"页"这件事：画布 / 安全边距 / 字号阶梯。
#
# 与 Word 那套最大的不同：字号的量级差着一倍 ——
#   A4 正文 10.5pt 是给三十厘米外的人读的；幻灯片字号是给三米外的人看的。
#   照 Word 的字号做幻灯片，投出来就是"看不见"。这条不写下来，下一个人一定会照抄。

#: 画布 16:9（cm）。判据是"投影幕布与显示器都是这个比例"，不是"看着宽一点"：
#: 4:3 投到 16:9 的屏上，左右各留一条黑边。
#: `python-pptx` 的 `Presentation()` 默认模板是 4:3（25.4 × 19.05）
#: —— 不显式设这两个值，产出的每一份都是 4:3。
DECK_WIDTH_CM = 33.867
DECK_HEIGHT_CM = 19.05

#: 安全边距（cm）—— 内容离页边至少这么远。
#: 判据：投影会裁边、装订会压边、有的会议室还在用 4:3 的机器放 16:9 的片子。
#: 元素贴到页边上，投出来就会被切掉一条。
DECK_MARGIN_CM = 1.27          # = 0.5 in，整数英寸好算，也够宽

#: 字号阶梯（pt）。标题给得比正文大一倍是刻意的：幻灯片的层级
#: 靠距离也靠字号，三米外看不清"加粗了没"。
DECK_TITLE_PT = 32.0
DECK_SUBTITLE_PT = 20.0
DECK_BODY_PT = 18.0
DECK_CAPTION_PT = 14.0

#: 可读性下限。低于它就不是"小字"，是"看不见"。
#: 体检打在这一档，因为它是唯一能机械判的：「够不够大」没有客观线，
#: 而「比 12pt 还小」有。（同 `layout_spec` 那段判据的风格：判据要能机检。）
DECK_MIN_FONT_PT = 12.0

#: 正文与标题的最小倍数。判据同上："层级看得出来"要有个能做减法的地方。
DECK_TITLE_RATIO = 1.4

#: 幻灯片上允许出现的文字色，最多几种。
#:
#: **判据不能写成「文字色必须在 `(INK, INK_MUTED, ACCENT)` 里」** ——
#: 那是 Word 文书那套身份。而幻灯片的配色是按视觉风格现选的
#: （上游 19 种风格；瑞士国际主义那一档用 `#111111` / `#6B6B6B`
#: 完全合理），那个判据会在真实产物上报假阳性。
#:判据是「数得清」，不是「必须等于」。一条老规矩：
#: 一个每次都报红的体检器，两天就没人看了。
#: 保留下来的硬线只有一条：不用纯黑（同 Word 那条，理由一样）。
DECK_MAX_TEXT_COLORS = 3
