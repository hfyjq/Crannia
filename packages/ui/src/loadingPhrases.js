// 状态横幅上那句「正在干什么」（`构思中…` / `深度思考…` / `整理中…`）。
//
// 内容与仓库根的 `加载随机句.txt` 同源，但目前是硬编码 ——
//   这是一处已知的两套真相源：改 txt 不会改到这里。
//   正解是让后端发一个只读端点、前端去取（这样用户改 txt 即时生效）；
//   今天先硬编码。
export const LOADING_PHRASES = [
  "解释中", "修饰语句", "正在思考", "阐明想法", "构思中", "思考中", "工作中", "操作中",
  "尝试理解", "沉思中", "进行推理", "生成中", "尝试中", "整理中", "计算中", "正在执行",
  "深度思考", "编写中", "编写文件", "输入中", "理清思路", "处理中",
];

export function randomLoadingPhrase() {
  return LOADING_PHRASES[Math.floor(Math.random() * LOADING_PHRASES.length)];
}
